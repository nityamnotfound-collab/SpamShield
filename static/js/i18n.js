Object.keys(translations.hi).forEach((key) => {
    translations.en[key] = key;
});

let currentLanguage = localStorage.getItem("spamshield-language") === "hi"
    ? "hi"
    : "en";

function t(key, values) {
    const message = translations[currentLanguage][key]
        || translations.en[key]
        || key;
    return message.replace(/\{(\w+)\}/g, (match, name) => {
        return values && values[name] !== undefined
            ? String(values[name])
            : match;
    });
}

function applyLanguage() {
    document.documentElement.lang = currentLanguage;
    const title = document.querySelector("title");
    if (title) {
        if (title.dataset.i18nOriginal === undefined) {
            title.dataset.i18nOriginal = title.textContent.trim();
        }
        title.textContent = t(title.dataset.i18nOriginal);
    }

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        if (!element.dataset.i18n) {
            return;
        }
        const values = {};
        if (element.dataset.i18nName !== undefined) {
            values.name = element.dataset.i18nName;
        }
        element.textContent = t(element.dataset.i18n, values);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        element.placeholder = t(element.dataset.i18nPlaceholder);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
        element.setAttribute("aria-label", t(element.dataset.i18nAria));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((element) => {
        element.title = t(element.dataset.i18nTitle);
    });
    document.querySelectorAll("[data-i18n-content]").forEach((element) => {
        element.content = t(element.dataset.i18nContent);
    });
    document.querySelectorAll("[data-i18n-dynamic]").forEach((element) => {
        if (element.dataset.i18nOriginal === undefined) {
            element.dataset.i18nOriginal = element.textContent.trim();
        }
        element.textContent = t(element.dataset.i18nOriginal);
    });
    document.querySelectorAll("[data-language-choice]").forEach((button) => {
        button.setAttribute(
            "aria-pressed",
            String(button.dataset.languageChoice === currentLanguage)
        );
    });
}

function setLanguage(language) {
    currentLanguage = language === "hi" ? "hi" : "en";
    localStorage.setItem("spamshield-language", currentLanguage);
    applyLanguage();
    window.dispatchEvent(
        new CustomEvent("spamshield:languagechange", {
            detail: { language: currentLanguage },
        })
    );
}

window.t = t;
window.getCurrentLanguage = () => currentLanguage;
window.setLanguage = setLanguage;
window.addEventListener("storage", (event) => {
    if (event.key === "spamshield-language") {
        currentLanguage = event.newValue === "hi" ? "hi" : "en";
        applyLanguage();
        window.dispatchEvent(
            new CustomEvent("spamshield:languagechange", {
                detail: { language: currentLanguage },
            })
        );
    }
});
document.querySelectorAll("[data-language-choice]").forEach((button) => {
    button.addEventListener("click", () => {
        setLanguage(button.dataset.languageChoice);
    });
});
applyLanguage();
